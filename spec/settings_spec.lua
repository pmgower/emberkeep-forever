local Settings = dofile("Kinfolk/Core/Settings.lua")

describe("Settings.Apply", function()
  it("fills in every default on first run", function()
    local s = Settings.Apply({})
    assert.is_true(s.minimapButton)
    assert.is_false(s.locked)
    assert.are.equal("frost", s.theme)
    assert.are.equal(1.0, s.scale)
  end)

  it("keeps the player's choices", function()
    local s = Settings.Apply({ minimapButton = false, theme = "twilight", scale = 1.2 })
    assert.is_false(s.minimapButton)
    assert.are.equal("twilight", s.theme)
    assert.are.equal(1.2, s.scale)
  end)

  it("pulls a broken or out-of-range scale back in range", function()
    assert.are.equal(0.7, Settings.Apply({ scale = 0 }).scale)
    assert.are.equal(1.5, Settings.Apply({ scale = 9 }).scale)
    assert.are.equal(1.0, Settings.Apply({ scale = "big" }).scale)
  end)
end)

describe("Settings.ScaleLabel", function()
  it("reads as a percent", function()
    assert.are.equal("100%", Settings.ScaleLabel(1))
    assert.are.equal("85%", Settings.ScaleLabel(0.85))
  end)
end)
